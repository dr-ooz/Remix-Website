// remix-data/dex_order.json (from the dex order board) -> src/js/remix_dex_order.js
// REMIX_DEX_ORDER: calc species name -> position in the Remix dex. The calc's Pokemon list sorts by it.
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..");
const order = JSON.parse(fs.readFileSync(path.join(root, "remix-data", "dex_order.json"), "utf8"));
const pos = {};
let n = 0;
for (const fam of order.main.families) for (const name of fam.members) if (!(name in pos)) pos[name] = n++;
// board names that the calc spells differently
const ALIAS = { "Zygarde-50%": "Zygarde", "Basculin-Blue": "Basculin-Blue-Striped", "Minior": "Minior-Meteor" };
for (const [a, b] of Object.entries(ALIAS)) if (a in pos && !(b in pos)) pos[b] = pos[a];
const js = "// Generated by tools/build_dex_order.js from remix-data/dex_order.json. Do not edit.\n" +
  "var REMIX_DEX_ORDER = " + JSON.stringify(pos) + ";\n";
fs.writeFileSync(path.join(root, "src", "js", "remix_dex_order.js"), js);
console.log("dex order: " + n + " Pokemon");
