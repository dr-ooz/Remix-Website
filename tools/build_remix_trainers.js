// Builds the calc's trainer sets + Boss Guide data (runs on every `npm run compile`).
// remix-data/trainers.json      -> every trainer team (tools/export_trainers.py, straight from the romfs)
// remix-data/trainer_notes.json -> which trainers to include, labels, titles, notes (hand-edited)
// remix-data/move_blurbs.json   -> short move notes (tools/build_move_blurbs.py)
// remix-data/item_descs.json    -> item hover text (tools/refresh_item_names.py)
// Output: src/js/data/sets/gen7.js (SETDEX_SM) and src/js/remix_guide_data.js (generated, don't edit by hand).
"use strict";
const fs = require("fs");
const path = require("path");
const ROOT = path.join(__dirname, "..");
const read = (f, d) => { const p = path.join(ROOT, "remix-data", f); return fs.existsSync(p) ? JSON.parse(fs.readFileSync(p, "utf8")) : d; };
const trainers = read("trainers.json", []);
const cfg = read("trainer_notes.json", {});
const notes = cfg.trainers || {};
const setdex = {}, info = {};
let skipped = 0, count = 0;
for (const t of trainers) {
	const n = notes[t.id] || {};
	if (n.hide || (!t.boss && !cfg.includeRegularTrainers && !n.label)) continue;
	const label = n.label || (t.name + " #" + t.id);
	info[label] = {id: t.id, cls: t.class, title: n.title || (t.class + " " + t.name), notes: n.notes || "",
		mons: n.mons || {}, doubles: !!t.doubles, boss: t.boss, team: t.team.map(m => m.species)};
	t.team.forEach((m, i) => {
		setdex[m.species] = setdex[m.species] || {};
		if (setdex[m.species][label]) { skipped++; return; } // same species twice on one team
		const evs = {}, ivs = {};
		for (const s in m.evs) if (m.evs[s]) evs[s] = m.evs[s];
		for (const s in m.ivs) if (m.ivs[s] !== 31) ivs[s] = m.ivs[s];
		setdex[m.species][label] = {level: m.level, ability: m.ability, item: m.item || undefined, nature: m.nature,
			moves: m.moves, evs, ivs, sub_index: i};
		count++;
	});
}
const header = "// GENERATED by tools/build_remix_trainers.js from remix-data/trainers.json. Do not edit by hand.\n";
fs.writeFileSync(path.join(ROOT, "src", "js", "data", "sets", "gen7.js"), header + "var SETDEX_SM = " + JSON.stringify(setdex) + ";\n");
const abilities = read("abilities.json", []);
const abilityDescs = {};
for (const a of abilities) if (a[0]) abilityDescs[String(a[0]).replace(/’/g, "'")] = String(a[1] || "").replace(/\s+/g, " ");
// Switch-in AI move power (Battle.cro Rule30, EBP 0x1237F0): BP (<10 -> 60) x hits (2-5 -> 3, fixed N -> N)
// x1.5 if always-crit. No STAB/items/abilities. Shown as the guide's BP so players can prep switch-ins.
const extras = read("move_extras.json", {});
const aiBP = {};
for (const m of read("moves.json", [])) {
	const x = extras[m.num];
	if (!m.name || !x || m.category === 0 || !m.power) continue;
	const bp = m.power < 10 ? 60 : m.power;
	const hits = x.hitMax === 5 ? 3 : Math.max(1, x.hitMax);
	const crit = x.crit >= 6;
	aiBP[m.name.replace(/’/g, "'")] = [Math.floor(bp * hits * (crit ? 1.5 : 1)), bp, hits, crit ? 1 : 0];
}
const moveDescs = {};
for (const m of read("moves.json", [])) if (m.name) moveDescs[m.name.replace(/’/g, "'")] = String(m.desc || "").replace(/\s+/g, " ");
const blurbs = {};
for (const [k, v] of Object.entries(read("move_blurbs.json", {}))) blurbs[k.replace(/’/g, "'")] = v;
fs.writeFileSync(path.join(ROOT, "src", "js", "remix_guide_data.js"), header +
	"var REMIX_TRAINER_INFO = " + JSON.stringify(info) + ";\n" +
	"var REMIX_MOVE_BLURBS = " + JSON.stringify(blurbs) + ";\n" +
	"var REMIX_MOVE_AI_BP = " + JSON.stringify(aiBP) + "; // [AI BP, base, hits, always-crit]\n" +
	"var REMIX_MOVE_DESCS = " + JSON.stringify(moveDescs) + ";\n" +
	"var REMIX_ABILITY_DESCS = " + JSON.stringify(abilityDescs) + ";\n" +
	"var REMIX_ITEM_DESCS = " + JSON.stringify(read("item_descs.json", {})) + ";\n" +
	"var REMIX_ITEM_SUMMARIES = " + JSON.stringify(cfg.itemSummaries || {}) + ";\n" +
	"// Layout edits made in the guide's Edit mode, saved with \"Save to file\" (remix-data/guide_edits.json)\n" +
	"var REMIX_GUIDE_EDITS = " + JSON.stringify(read("guide_edits.json", {})) + ";\n");
console.log("Remix trainers: " + Object.keys(info).length + " trainers, " + count + " sets -> gen7.js" + (skipped ? " (" + skipped + " duplicate species skipped)" : ""));
