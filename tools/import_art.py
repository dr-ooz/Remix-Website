"""Import Pokemon art (Dreamworld / Global Link style) for the Boss Guide.

Takes a folder of PNGs named like "001_Slakoth.png", "025_MegaAlakazam.png", "302_Georupt(Geodude).png",
matches each to a calc species, and writes src/img/art/<id>.webp (max 300px tall) plus
src/js/remix_art.js (the list of local art, so the page only asks the web for the rest).
Re-run any time; existing files are overwritten. Unmatched files are listed - add them to ALIASES.

Usage:  python tools/import_art.py "<art folder>" [more folders...]
"""
import json, os, re, subprocess, sys
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "src", "img", "art")
# file name (after the number, before "(") -> calc species name
ALIASES = {"Mewtwo_Y": "Mewtwo-Mega", "MeloettaAria": "Meloetta", "BasculinRed": "Basculin",
           "BasculinBlue": "Basculin-Blue-Striped", "MegaAlolanPersian": "Persian-Mega",
           "VivillonSnow": "Vivillon"}
toid = lambda s: re.sub(r"[^a-z0-9]", "", s.lower())


def species_names():
    js = "const g=require('./calc/dist/index.js').Generations.get(7);console.log(JSON.stringify([...g.species].map(s=>s.name)))"
    return json.loads(subprocess.check_output(["node", "-e", js], cwd=ROOT))


def match(stem, ids):
    stem = re.sub(r"^\d+_?", "", stem).split("(")[0].strip()
    if stem in ALIASES: return toid(ALIASES[stem])
    t = toid(stem)
    cands = [t]
    m = re.match(r"(Mega|Alolan)(.+)", stem)
    if m and stem != "Meganium":
        base = toid(m.group(2))
        cands = [base + ("mega" if m.group(1) == "Mega" else "alola"), base] if m.group(1) == "Alolan" else [base + "mega"]
    for c in cands:
        if c in ids: return c
    pre = [i for i in ids if i.startswith(t)]
    return pre[0] if len(pre) == 1 else None


def main(folders):
    ids = {toid(n) for n in species_names()}
    os.makedirs(OUT, exist_ok=True)
    done, missed = set(), []
    for folder in folders:
        for f in sorted(os.listdir(folder)):
            if not f.lower().endswith(".png") or f.startswith("!"): continue
            sid = match(os.path.splitext(f)[0], ids)
            if not sid:  # not a calc species: keep it under its own name
                missed.append(f); sid = toid(re.sub(r"^\d+_?", "", f[:-4]).split("(")[0])
            im = Image.open(os.path.join(folder, f)).convert("RGBA")
            im = im.crop(im.getbbox() or (0, 0, im.width, im.height))
            if im.height > 300: im = im.resize((round(im.width * 300 / im.height), 300), Image.LANCZOS)
            im.save(os.path.join(OUT, sid + ".webp"), "WEBP", quality=88, method=6)
            done.add(sid)
    have = sorted(f[:-5] for f in os.listdir(OUT) if f.endswith(".webp"))
    open(os.path.join(ROOT, "src", "js", "remix_art.js"), "w").write(
        "// GENERATED by tools/import_art.py - Pokemon with local art in img/art/<id>.webp\n"
        "var REMIX_ART = " + json.dumps(have) + ";\n")
    print("imported %d, %d local art total" % (len(done), len(have)))
    if missed: print("not calc species, saved by file name:", ", ".join(missed))


if __name__ == "__main__":
    main(sys.argv[1:])
